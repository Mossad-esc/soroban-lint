#!/usr/bin/env bash
# scripts/corpus.sh — run soroban-lint against a set of real open-source
# Soroban contracts and produce a machine-readable JSON report per project.
#
# Usage:
#   bash scripts/corpus.sh [--update-sources]
#
# The script:
#   1. Creates (or reuses) corpus/ at the workspace root, which is git-ignored.
#   2. Shallow-clones each project listed in SOURCES at the pinned commit hash.
#   3. Runs `soroban-lint check --format json` on each project.
#   4. Writes per-project JSON to corpus/<slug>/findings.json.
#   5. Writes corpus/SOURCES.md with repo URLs, commit hashes, and licenses.
#   6. Prints a summary table to stdout.
#
# Requirements:
#   - git must be in PATH.
#   - soroban-lint must be in PATH or built in target/release or target/debug.
#
# The corpus/ directory is listed in .gitignore and is never committed.
# docs/corpus-report.md is the human-readable analysis; edit it after running
# this script.
#
# To add a new project, append a line to the SOURCES array below and re-run.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKSPACE="${SCRIPT_DIR}/.."
CORPUS_DIR="${WORKSPACE}/corpus"
SOURCES_MD="${CORPUS_DIR}/SOURCES.md"

# ── Locate the binary ────────────────────────────────────────────────────────
BINARY=""
if command -v soroban-lint >/dev/null 2>&1; then
    BINARY="soroban-lint"
elif [[ -x "${WORKSPACE}/target/release/soroban-lint" ]]; then
    BINARY="${WORKSPACE}/target/release/soroban-lint"
elif [[ -x "${WORKSPACE}/target/debug/soroban-lint" ]]; then
    BINARY="${WORKSPACE}/target/debug/soroban-lint"
else
    echo "error: soroban-lint binary not found." \
         "Run 'cargo build --release' first or install it with 'cargo install --path crates/lint-cli'." >&2
    exit 2
fi

echo "Binary: $BINARY"

# ── Source list ──────────────────────────────────────────────────────────────
# Format: "slug|url|commit_hash|license|description"
#
# Commit hashes are pinned so corpus runs are reproducible.  To update a hash,
# run 'git ls-remote <url> HEAD' and paste the new SHA here, then re-run this
# script and update docs/corpus-report.md.
#
# All projects use permissive licenses (Apache-2.0 or MIT).
SOURCES=(
    "soroban-examples|https://github.com/stellar/soroban-examples|03d42aa6b973dcf3a453a99d0c6a6e8d25a196e2|Apache-2.0|Official Stellar Soroban examples"
    "soroswap-core|https://github.com/soroswap/core|6eade008ee6794075ad941609e0fef0d1124d3eb|Apache-2.0|Soroswap DEX core contracts"
    "blend-contracts-v2|https://github.com/blend-capital/blend-contracts-v2|0bf9b74d22affa230554c0422d29936011c61e75|MIT|Blend Protocol v2 lending contracts"
)

# ── Helpers ──────────────────────────────────────────────────────────────────
clone_or_update() {
    local slug="$1"
    local url="$2"
    local commit="$3"
    local dest="${CORPUS_DIR}/${slug}"

    if [[ -d "${dest}/.git" ]]; then
        # Already cloned.  Check whether the pinned commit is present.
        local current
        current=$(git -C "${dest}" rev-parse HEAD 2>/dev/null || echo "unknown")
        if [[ "${current}" == "${commit}" ]]; then
            echo "  [skip] ${slug}: already at pinned commit ${commit:0:12}"
            return 0
        fi
        echo "  [update] ${slug}: re-cloning to get ${commit:0:12}"
        rm -rf "${dest}"
    fi

    echo "  [clone] ${slug}: ${url} @ ${commit:0:12}"
    git clone --quiet --depth=1 "${url}" "${dest}" 2>&1 | tail -3

    # Fetch the exact pinned commit (shallow clone may not have it if branch
    # has moved forward; unshallow and then reset).
    local actual
    actual=$(git -C "${dest}" rev-parse HEAD 2>/dev/null || echo "unknown")
    if [[ "${actual}" != "${commit}" ]]; then
        echo "  [pin] ${slug}: fetching exact commit ${commit:0:12}"
        git -C "${dest}" fetch --quiet --unshallow origin "${commit}" 2>/dev/null || \
            git -C "${dest}" fetch --quiet origin "${commit}" 2>/dev/null || true
        git -C "${dest}" checkout --quiet "${commit}" 2>/dev/null || true
    fi
}

# ── Main ─────────────────────────────────────────────────────────────────────
mkdir -p "${CORPUS_DIR}"

echo ""
echo "=== Corpus setup ==="
for entry in "${SOURCES[@]}"; do
    IFS='|' read -r slug url commit _license _desc <<< "${entry}"
    clone_or_update "${slug}" "${url}" "${commit}"
done

# Write SOURCES.md (overwritten each run for accuracy).
cat > "${SOURCES_MD}" << 'HEREDOC'
# corpus/SOURCES.md

This file is auto-generated by `scripts/corpus.sh`.  Do not edit by hand.

It records every project in the corpus: URL, pinned commit hash, license, and
a brief description.  Commit hashes are pinned so corpus runs are reproducible;
update them by running `git ls-remote <url> HEAD` and re-running the script.

HEREDOC

echo "| Slug | Repository | Commit | License | Description |" >> "${SOURCES_MD}"
echo "|------|-----------|--------|---------|-------------|" >> "${SOURCES_MD}"
for entry in "${SOURCES[@]}"; do
    IFS='|' read -r slug url commit license desc <<< "${entry}"
    echo "| \`${slug}\` | [${url}](${url}) | \`${commit:0:12}\` | ${license} | ${desc} |" >> "${SOURCES_MD}"
done

echo ""
echo "=== Running soroban-lint on corpus ==="

# Aggregate statistics.
declare -A TOTAL_ERRORS TOTAL_WARNINGS TOTAL_NOTES TOTAL_FILES

for entry in "${SOURCES[@]}"; do
    IFS='|' read -r slug _url _commit _license _desc <<< "${entry}"
    dest="${CORPUS_DIR}/${slug}"
    findings_json="${dest}/findings.json"

    if [[ ! -d "${dest}" ]]; then
        echo "  [skip] ${slug}: directory not present (clone failed?)"
        continue
    fi

    echo -n "  ${slug}: "

    # Run the linter; exit 0 or 1 are fine (0 = clean, 1 = findings).
    # Exit 2 is an internal error; we capture it and note it.
    set +e
    "${BINARY}" check "${dest}" --format json > "${findings_json}" 2>&1
    lint_exit=$?
    set -e

    if [[ ${lint_exit} -eq 2 ]]; then
        echo "INTERNAL ERROR (exit 2) — see ${findings_json}"
        TOTAL_ERRORS["${slug}"]="ERR"
        TOTAL_WARNINGS["${slug}"]="ERR"
        TOTAL_NOTES["${slug}"]="ERR"
        TOTAL_FILES["${slug}"]="ERR"
        continue
    fi

    # Parse summary from JSON output.
    if command -v python3 >/dev/null 2>&1; then
        read -r errors warnings notes files_scanned <<< "$(python3 - "${findings_json}" << 'PYEOF'
import sys, json
try:
    with open(sys.argv[1]) as f:
        d = json.load(f)
    s = d.get("summary", {})
    print(s.get("errors", 0), s.get("warnings", 0), s.get("notes", 0), s.get("files_scanned", 0))
except Exception as e:
    print(0, 0, 0, 0)
PYEOF
)"
    else
        errors=0; warnings=0; notes=0; files_scanned=0
    fi

    TOTAL_ERRORS["${slug}"]="${errors}"
    TOTAL_WARNINGS["${slug}"]="${warnings}"
    TOTAL_NOTES["${slug}"]="${notes}"
    TOTAL_FILES["${slug}"]="${files_scanned}"

    echo "${files_scanned} files, ${errors} errors, ${warnings} warnings, ${notes} notes"
done

# ── Summary table ────────────────────────────────────────────────────────────
echo ""
echo "=== Summary ==="
printf "%-30s %8s %8s %8s %8s\n" "Project" "Files" "Errors" "Warnings" "Notes"
printf "%-30s %8s %8s %8s %8s\n" "-------" "-----" "------" "--------" "-----"
for entry in "${SOURCES[@]}"; do
    IFS='|' read -r slug _url _commit _license _desc <<< "${entry}"
    printf "%-30s %8s %8s %8s %8s\n" \
        "${slug}" \
        "${TOTAL_FILES[${slug}]:-0}" \
        "${TOTAL_ERRORS[${slug}]:-0}" \
        "${TOTAL_WARNINGS[${slug}]:-0}" \
        "${TOTAL_NOTES[${slug}]:-0}"
done

echo ""
echo "Per-project findings JSON written to corpus/<slug>/findings.json"
echo "Update docs/corpus-report.md with real triage results after reviewing these files."
echo "Done."
